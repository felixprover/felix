textFilterSupportScript :: Text
textFilterSupportScript = Text.unlines
    [ "const createTextFilter = (entries, textOf = (item) => item.textContent || '') => {"
    , "  const labels = new Map(entries.map((item) => [item, textOf(item).trim().toLowerCase()]));"
    , "  let query = '';"
    , "  return {"
    , "    setQuery(value) { query = value.trim().toLowerCase(); },"
    , "    matches(item) { return query === '' || (labels.get(item) || '').includes(query); }"
    , "  };"
    , "};"
    ]

declarationIndexScript :: Text
declarationIndexScript = Text.unlines
    [ "(function () {"
    , "  const list = document.querySelector('.declaration-list');"
    , "  if (!list) return;"
    , "  const entries = Array.from(list.querySelectorAll(':scope > li'));"
    , "  if (!entries.length) return;"
    , "  const controls = document.createElement('div');"
    , "  controls.className = 'declaration-filter-controls';"
    , "  const labelledControl = (labelText, control) => {"
    , "    const label = document.createElement('label');"
    , "    const text = document.createElement('span');"
    , "    text.textContent = labelText;"
    , "    label.append(text, control);"
    , "    return label;"
    , "  };"
    , "  const search = document.createElement('input');"
    , "  search.type = 'search';"
    , "  search.placeholder = 'Marker or title';"
    , "  const kind = document.createElement('select');"
    , "  const theory = document.createElement('select');"
    , "  const textFilter = createTextFilter(entries);"
    , "  const addOptions = (select, values, allLabel) => {"
    , "    const all = document.createElement('option');"
    , "    all.value = '';"
    , "    all.textContent = allLabel;"
    , "    select.append(all);"
    , "    for (const value of values) {"
    , "      const option = document.createElement('option');"
    , "      option.value = value;"
    , "      option.textContent = value;"
    , "      select.append(option);"
    , "    }"
    , "  };"
    , "  const distinct = (attribute) => Array.from(new Set(entries.map((item) => item.getAttribute(attribute) || ''))).filter(Boolean).sort((a, b) => a.localeCompare(b));"
    , "  addOptions(kind, distinct('data-declaration-kind'), 'All kinds');"
    , "  addOptions(theory, distinct('data-declaration-theory'), 'All theories');"
    , "  controls.append(labelledControl('Find declarations', search), labelledControl('Kind', kind), labelledControl('Theory', theory));"
    , "  const status = document.createElement('p');"
    , "  status.className = 'declaration-filter-status';"
    , "  status.setAttribute('aria-live', 'polite');"
    , "  list.before(controls, status);"
    , "  const noResults = document.querySelector('.declaration-no-results');"
    , "  const apply = () => {"
    , "    textFilter.setQuery(search.value);"
    , "    let visible = 0;"
    , "    for (const item of entries) {"
    , "      const matchesText = textFilter.matches(item);"
    , "      const matchesKind = kind.value === '' || item.getAttribute('data-declaration-kind') === kind.value;"
    , "      const matchesTheory = theory.value === '' || item.getAttribute('data-declaration-theory') === theory.value;"
    , "      item.hidden = !(matchesText && matchesKind && matchesTheory);"
    , "      if (!item.hidden) visible += 1;"
    , "    }"
    , "    status.textContent = `${visible} of ${entries.length} declarations`;"
